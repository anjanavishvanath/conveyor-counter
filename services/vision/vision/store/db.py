"""
services/vision/vision/store/db.py

SQLite persistence for batches, counts and events.

Why it looks like this
  * The vision service owns this database. It is the only writer; the API reads it.
  * WAL mode + synchronous=FULL: a batch's running count must survive a power loss,
    because the operator has to know how many coconuts really went into the crate.
  * Writes never happen on the camera/inference loop. `StoreWriter` owns a thread and a
    queue; the loop only enqueues. A slow or busy disk can therefore never stall counting
    or delay the run-permit decision.
  * Every batch has a UUID, every timestamp is epoch seconds UTC, and `synced` is reserved
    for a later cloud push. Records from many plants can be merged without collisions.

Durability limit worth knowing: a power loss drops whatever is still in the writer queue
(normally the last few milliseconds). A restart during a batch therefore always marks that
batch `uncertain`, so the count is flagged for review rather than quietly trusted.
"""
from __future__ import annotations

import json
import logging
import queue
import sqlite3
import threading
from contextlib import contextmanager
from datetime import date, datetime, timedelta
from pathlib import Path
from typing import Any, Callable, Dict, Iterable, List, Optional, Tuple
from zoneinfo import ZoneInfo

log = logging.getLogger("store")

SCHEMA_VERSION = 1

_SCHEMA = """
CREATE TABLE IF NOT EXISTS meta (
    key   TEXT PRIMARY KEY,
    value TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS batches (
    batch_id          TEXT PRIMARY KEY,          -- UUID, generated by the controller
    site_name         TEXT NOT NULL,
    product           TEXT NOT NULL,
    crate             INTEGER NOT NULL,
    target            INTEGER NOT NULL,
    count             INTEGER NOT NULL DEFAULT 0,
    status            TEXT NOT NULL,             -- open | completed | aborted
    uncertain         INTEGER NOT NULL DEFAULT 0,-- a fault or restart happened: review the count
    frames_lost       INTEGER NOT NULL DEFAULT 0,
    created_at        REAL NOT NULL,             -- epoch seconds, UTC
    started_at        REAL,
    target_reached_at REAL,
    completed_at      REAL,
    faults            TEXT NOT NULL DEFAULT '[]',
    stops             TEXT NOT NULL DEFAULT '[]',
    product_profile   TEXT,                      -- which profile/model produced this count
    model_file        TEXT,
    detector          TEXT,                      -- onnx_cpu | qnn_htp ...
    recovered         INTEGER NOT NULL DEFAULT 0,-- re-adopted after a restart
    synced            INTEGER NOT NULL DEFAULT 0 -- reserved for a later central sync
);
CREATE INDEX IF NOT EXISTS idx_batches_created ON batches(created_at);
CREATE INDEX IF NOT EXISTS idx_batches_status  ON batches(status);
CREATE INDEX IF NOT EXISTS idx_batches_crate   ON batches(crate, created_at);

-- One row per count event: the audit trail behind a batch total, and the source
-- for throughput-per-hour reporting.
CREATE TABLE IF NOT EXISTS counts (
    batch_id TEXT NOT NULL,
    count    INTEGER NOT NULL,                   -- running total AFTER this event
    added    INTEGER NOT NULL,
    ts       REAL NOT NULL,
    PRIMARY KEY (batch_id, count)                -- replaying an event cannot inflate the total
);
CREATE INDEX IF NOT EXISTS idx_counts_ts ON counts(ts);

CREATE TABLE IF NOT EXISTS events (
    id       INTEGER PRIMARY KEY AUTOINCREMENT,
    ts       REAL NOT NULL,
    kind     TEXT NOT NULL,                      -- state_changed | fault | batch_completed | ...
    batch_id TEXT,
    payload  TEXT NOT NULL DEFAULT '{}'
);
CREATE INDEX IF NOT EXISTS idx_events_ts    ON events(ts);
CREATE INDEX IF NOT EXISTS idx_events_batch ON events(batch_id, id);

-- Manual corrections. The machine count is never edited in place: a correction is a
-- separate, attributed row, so the original number is always recoverable.
CREATE TABLE IF NOT EXISTS corrections (
    id         INTEGER PRIMARY KEY AUTOINCREMENT,
    batch_id   TEXT NOT NULL,
    ts         REAL NOT NULL,
    delta      INTEGER NOT NULL,
    reason     TEXT NOT NULL DEFAULT '',
    author     TEXT NOT NULL DEFAULT '',
    FOREIGN KEY (batch_id) REFERENCES batches(batch_id)
);
CREATE INDEX IF NOT EXISTS idx_corrections_batch ON corrections(batch_id);
"""

BATCH_COLUMNS = (
    "batch_id", "site_name", "product", "crate", "target", "count", "status", "uncertain",
    "frames_lost", "created_at", "started_at", "target_reached_at", "completed_at",
    "faults", "stops", "product_profile", "model_file", "detector", "recovered", "synced",
)


# ───────────────────────── production day helpers ─────────────────────────
def parse_day_start(day_start: str) -> Tuple[int, int]:
    hh, mm = day_start.split(":")
    return int(hh), int(mm)


def production_day_bounds(day: date, tz_name: str, day_start: str = "00:00") -> Tuple[float, float]:
    """
    [start, end) epoch seconds of one production day.

    A plant whose shift starts at 06:00 sets day_start="06:00": the production day
    2026-10-18 then runs 2026-10-18 06:00 local to 2026-10-19 06:00 local, so a shift
    that crosses midnight is not split in half.
    """
    tz = ZoneInfo(tz_name)
    hh, mm = parse_day_start(day_start)
    start = datetime(day.year, day.month, day.day, hh, mm, tzinfo=tz)
    return start.timestamp(), (start + timedelta(days=1)).timestamp()


def production_day_of(ts: float, tz_name: str, day_start: str = "00:00") -> date:
    """Which production day an instant belongs to."""
    tz = ZoneInfo(tz_name)
    local = datetime.fromtimestamp(ts, tz)
    hh, mm = parse_day_start(day_start)
    if (local.hour, local.minute) < (hh, mm):
        local -= timedelta(days=1)
    return local.date()


# ───────────────────────── store ─────────────────────────
class Store:
    """
    Thread-safe SQLite access: one connection per thread, autocommit, explicit
    transactions where several statements must land together.
    """

    def __init__(self, path: str | Path, synchronous: str = "FULL", timeout_s: float = 5.0):
        self.path = Path(path)
        self.synchronous = synchronous
        self.timeout_s = timeout_s
        self._local = threading.local()
        self._conns: List[sqlite3.Connection] = []
        self._conns_lock = threading.Lock()
        self.path.parent.mkdir(parents=True, exist_ok=True)

    # ── connection ──
    def _conn(self) -> sqlite3.Connection:
        c = getattr(self._local, "conn", None)
        if c is None:
            c = sqlite3.connect(str(self.path), timeout=self.timeout_s, isolation_level=None)
            c.row_factory = sqlite3.Row
            c.execute("PRAGMA journal_mode=WAL")
            c.execute(f"PRAGMA synchronous={self.synchronous}")
            c.execute("PRAGMA busy_timeout=5000")
            c.execute("PRAGMA foreign_keys=ON")
            self._local.conn = c
            with self._conns_lock:
                self._conns.append(c)
        return c

    @contextmanager
    def _tx(self):
        c = self._conn()
        c.execute("BEGIN IMMEDIATE")
        try:
            yield c
        except Exception:
            c.execute("ROLLBACK")
            raise
        else:
            c.execute("COMMIT")

    def migrate(self) -> None:
        c = self._conn()
        c.executescript(_SCHEMA)
        row = c.execute("SELECT value FROM meta WHERE key='schema_version'").fetchone()
        if row is None:
            c.execute("INSERT INTO meta(key, value) VALUES('schema_version', ?)", (str(SCHEMA_VERSION),))
        elif int(row["value"]) > SCHEMA_VERSION:
            raise RuntimeError(
                f"{self.path} was written by a newer version (schema {row['value']}, this build {SCHEMA_VERSION})"
            )
        log.info("database ready: %s (schema %d, synchronous=%s)", self.path, SCHEMA_VERSION, self.synchronous)

    def close(self) -> None:
        with self._conns_lock:
            for c in self._conns:
                try:
                    c.close()
                except Exception:
                    pass
            self._conns.clear()
        self._local = threading.local()

    # ── writes ──
    def save_batch(self, batch: Dict[str, Any], **extra: Any) -> None:
        """Insert or update a whole batch row. `batch` is the controller's Batch as a dict."""
        row = {k: batch.get(k) for k in BATCH_COLUMNS if k in batch}
        row.update({k: v for k, v in extra.items() if k in BATCH_COLUMNS})
        row["faults"] = json.dumps(batch.get("faults", []))
        row["stops"] = json.dumps(batch.get("stops", []))
        row["uncertain"] = int(bool(batch.get("uncertain", False)))
        row.setdefault("status", "open")
        row.setdefault("count", 0)
        row.setdefault("frames_lost", 0)
        cols = [c for c in BATCH_COLUMNS if c in row]
        placeholders = ", ".join("?" for _ in cols)
        updates = ", ".join(f"{c}=excluded.{c}" for c in cols if c != "batch_id")
        sql = (f"INSERT INTO batches ({', '.join(cols)}) VALUES ({placeholders}) "
               f"ON CONFLICT(batch_id) DO UPDATE SET {updates}")
        self._conn().execute(sql, [row[c] for c in cols])

    def save_count(self, batch_id: str, count: int, added: int, ts: float) -> None:
        """Record one count event and move the batch total, in a single transaction."""
        with self._tx() as c:
            c.execute("INSERT OR IGNORE INTO counts (batch_id, count, added, ts) VALUES (?, ?, ?, ?)",
                      (batch_id, count, added, ts))
            c.execute("UPDATE batches SET count=? WHERE batch_id=? AND count<?", (count, batch_id, count))

    def log_event(self, kind: str, ts: float, batch_id: Optional[str] = None,
                  payload: Optional[Dict[str, Any]] = None) -> None:
        self._conn().execute(
            "INSERT INTO events (ts, kind, batch_id, payload) VALUES (?, ?, ?, ?)",
            (ts, kind, batch_id, json.dumps(payload or {}, default=str)),
        )

    def add_correction(self, batch_id: str, delta: int, reason: str = "", author: str = "",
                       ts: Optional[float] = None) -> None:
        import time as _time
        self._conn().execute(
            "INSERT INTO corrections (batch_id, ts, delta, reason, author) VALUES (?, ?, ?, ?, ?)",
            (batch_id, ts if ts is not None else _time.time(), int(delta), reason, author),
        )

    def mark_recovered(self, batch_id: str) -> None:
        self._conn().execute("UPDATE batches SET recovered=1, uncertain=1 WHERE batch_id=?", (batch_id,))

    def abort_open_batches(self, except_id: Optional[str] = None) -> int:
        """Close stale open batches (e.g. several restarts in a row). Returns how many."""
        sql = "UPDATE batches SET status='aborted' WHERE status='open'"
        args: List[Any] = []
        if except_id:
            sql += " AND batch_id<>?"
            args.append(except_id)
        cur = self._conn().execute(sql, args)
        return cur.rowcount or 0

    # ── reads ──
    @staticmethod
    def _batch_row(row: sqlite3.Row) -> Dict[str, Any]:
        d = dict(row)
        d["faults"] = json.loads(d.get("faults") or "[]")
        d["stops"] = json.loads(d.get("stops") or "[]")
        d["uncertain"] = bool(d.get("uncertain"))
        d["recovered"] = bool(d.get("recovered"))
        d["overfill"] = max(0, (d.get("count") or 0) - (d.get("target") or 0))
        return d

    def open_batch(self) -> Optional[Dict[str, Any]]:
        """The batch left open by a crash or power loss (most recent, if several)."""
        row = self._conn().execute(
            "SELECT * FROM batches WHERE status='open' ORDER BY created_at DESC LIMIT 1"
        ).fetchone()
        return self._batch_row(row) if row else None

    def get_batch(self, batch_id: str) -> Optional[Dict[str, Any]]:
        row = self._conn().execute("SELECT * FROM batches WHERE batch_id=?", (batch_id,)).fetchone()
        return self._batch_row(row) if row else None

    def list_batches(self, since: Optional[float] = None, until: Optional[float] = None,
                     crate: Optional[int] = None, status: Optional[str] = None,
                     limit: int = 200, offset: int = 0) -> List[Dict[str, Any]]:
        sql = "SELECT * FROM batches WHERE 1=1"
        args: List[Any] = []
        if since is not None:
            sql += " AND created_at >= ?"
            args.append(since)
        if until is not None:
            sql += " AND created_at < ?"
            args.append(until)
        if crate is not None:
            sql += " AND crate = ?"
            args.append(crate)
        if status is not None:
            sql += " AND status = ?"
            args.append(status)
        sql += " ORDER BY created_at DESC LIMIT ? OFFSET ?"
        args += [int(limit), int(offset)]
        return [self._batch_row(r) for r in self._conn().execute(sql, args).fetchall()]

    def corrections_for(self, batch_id: str) -> List[Dict[str, Any]]:
        rows = self._conn().execute(
            "SELECT * FROM corrections WHERE batch_id=? ORDER BY id", (batch_id,)).fetchall()
        return [dict(r) for r in rows]

    def events_for(self, batch_id: str, limit: int = 500) -> List[Dict[str, Any]]:
        rows = self._conn().execute(
            "SELECT * FROM events WHERE batch_id=? ORDER BY id LIMIT ?", (batch_id, limit)).fetchall()
        out = []
        for r in rows:
            d = dict(r)
            d["payload"] = json.loads(d["payload"])
            out.append(d)
        return out

    def day_summary(self, day: date, tz_name: str, day_start: str = "00:00") -> Dict[str, Any]:
        start, end = production_day_bounds(day, tz_name, day_start)
        c = self._conn()
        totals = c.execute(
            """SELECT COUNT(*) AS batches,
                      COALESCE(SUM(count), 0) AS counted,
                      COALESCE(SUM(target), 0) AS targeted,
                      COALESCE(SUM(uncertain), 0) AS uncertain_batches
               FROM batches WHERE created_at >= ? AND created_at < ? AND status='completed'""",
            (start, end)).fetchone()
        per_crate = c.execute(
            """SELECT crate, COUNT(*) AS batches, COALESCE(SUM(count), 0) AS counted
               FROM batches WHERE created_at >= ? AND created_at < ? AND status='completed'
               GROUP BY crate ORDER BY crate""",
            (start, end)).fetchall()
        corr = c.execute(
            """SELECT COALESCE(SUM(delta), 0) AS delta FROM corrections
               WHERE ts >= ? AND ts < ?""", (start, end)).fetchone()
        return {
            "day": day.isoformat(),
            "start": start,
            "end": end,
            "timezone": tz_name,
            "day_start": day_start,
            "batches": totals["batches"],
            "counted": totals["counted"],
            "targeted": totals["targeted"],
            "uncertain_batches": totals["uncertain_batches"],
            "corrections": corr["delta"],
            "per_crate": [dict(r) for r in per_crate],
        }

    # ── CSV export ──
    CSV_HEADER = (
        "batch_id", "production_day", "crate", "target", "count", "overfill", "status",
        "uncertain", "recovered", "frames_lost", "created_local", "started_local",
        "completed_local", "duration_s", "corrections", "corrected_count",
        "faults", "stops", "detector", "model_file",
    )

    def export_rows(self, since: Optional[float], until: Optional[float], tz_name: str,
                    day_start: str = "00:00") -> Iterable[List[Any]]:
        """Rows for a CSV report. Local times are rendered with the site timezone."""
        tz = ZoneInfo(tz_name)

        def local(ts: Optional[float]) -> str:
            return datetime.fromtimestamp(ts, tz).strftime("%Y-%m-%d %H:%M:%S") if ts else ""

        for b in self.list_batches(since=since, until=until, limit=1_000_000):
            corr = sum(c["delta"] for c in self.corrections_for(b["batch_id"]))
            duration = ""
            if b["started_at"] and b["completed_at"]:
                duration = round(b["completed_at"] - b["started_at"], 1)
            yield [
                b["batch_id"],
                production_day_of(b["created_at"], tz_name, day_start).isoformat(),
                b["crate"], b["target"], b["count"], b["overfill"], b["status"],
                int(b["uncertain"]), int(b["recovered"]), b["frames_lost"],
                local(b["created_at"]), local(b["started_at"]), local(b["completed_at"]),
                duration, corr, b["count"] + corr,
                "; ".join(b["faults"]), "; ".join(b["stops"]),
                b.get("detector") or "", b.get("model_file") or "",
            ]


# ───────────────────────── asynchronous writer ─────────────────────────
class StoreWriter:
    """
    Serialises writes onto one background thread so the vision loop never touches the disk.

    `on_error` is called with the exception after `max_errors` consecutive failures; the
    service turns that into a FAULT, because counts that are not being persisted are
    exactly the silent-miscount case this system exists to remove.
    """

    MAX_QUEUE = 10_000

    def __init__(self, store: Store, on_error: Optional[Callable[[Exception], None]] = None,
                 max_errors: int = 3):
        self.store = store
        self.on_error = on_error
        self.max_errors = max_errors
        self._q: "queue.Queue[Optional[Tuple[str, tuple, dict]]]" = queue.Queue(maxsize=self.MAX_QUEUE)
        self._thread: Optional[threading.Thread] = None
        self._errors = 0
        self.dropped = 0

    # ── lifecycle ──
    def start(self) -> None:
        self._thread = threading.Thread(target=self._loop, name="store-writer", daemon=True)
        self._thread.start()

    def stop(self, timeout: float = 5.0) -> None:
        if self._thread is None:
            return
        self._q.put(None)
        self._thread.join(timeout=timeout)
        self._thread = None

    def flush(self, timeout: float = 5.0) -> bool:
        """Block until the queue is empty. Used before reporting a batch as saved."""
        done = threading.Event()
        try:
            self._q.put(("__barrier__", (done,), {}), timeout=timeout)
        except queue.Full:
            return False
        return done.wait(timeout)

    @property
    def backlog(self) -> int:
        return self._q.qsize()

    # ── enqueue ──
    def _submit(self, method: str, *args, **kwargs) -> None:
        try:
            self._q.put_nowait((method, args, kwargs))
        except queue.Full:
            self.dropped += 1
            log.error("store queue full; dropped %s (total dropped %d)", method, self.dropped)
            if self.on_error:
                self.on_error(RuntimeError("store queue full"))

    def save_batch(self, batch: Dict[str, Any], **extra: Any) -> None:
        self._submit("save_batch", dict(batch), **extra)

    def save_count(self, batch_id: str, count: int, added: int, ts: float) -> None:
        self._submit("save_count", batch_id, count, added, ts)

    def log_event(self, kind: str, ts: float, batch_id: Optional[str] = None,
                  payload: Optional[Dict[str, Any]] = None) -> None:
        self._submit("log_event", kind, ts, batch_id, payload)

    def mark_recovered(self, batch_id: str) -> None:
        self._submit("mark_recovered", batch_id)

    # ── thread ──
    def _loop(self) -> None:
        while True:
            item = self._q.get()
            if item is None:
                return
            method, args, kwargs = item
            if method == "__barrier__":
                args[0].set()
                continue
            try:
                getattr(self.store, method)(*args, **kwargs)
                self._errors = 0
            except Exception as e:  # noqa: BLE001 - the writer must not die
                self._errors += 1
                log.error("store write failed (%s, %d in a row): %s", method, self._errors, e)
                if self._errors >= self.max_errors and self.on_error:
                    self.on_error(e)


if __name__ == "__main__":
    # Quick look at what is in the database, and a CSV dump for one production day.
    import argparse
    import csv
    import sys

    from vision.config import load_config

    ap = argparse.ArgumentParser(description="Inspect the counter database")
    ap.add_argument("--config", default=None, help="path to site.yaml")
    ap.add_argument("--day", default=None, help="production day as YYYY-MM-DD (default: today)")
    ap.add_argument("--csv", default=None, help="write the day's batches to this CSV file ('-' for stdout)")
    args = ap.parse_args()

    cfg = load_config(args.config)
    store = Store(cfg.site.storage.db_path, synchronous=cfg.site.storage.synchronous)
    store.migrate()
    day = date.fromisoformat(args.day) if args.day else production_day_of(
        datetime.now().timestamp(), cfg.site.timezone, cfg.site.reporting.day_start)

    summary = store.day_summary(day, cfg.site.timezone, cfg.site.reporting.day_start)
    print(json.dumps(summary, indent=2))
    open_b = store.open_batch()
    print(f"\nopen batch: {open_b['batch_id'] if open_b else 'none'}"
          + (f" (crate {open_b['crate']}, {open_b['count']}/{open_b['target']})" if open_b else ""))

    if args.csv:
        out = sys.stdout if args.csv == "-" else open(args.csv, "w", newline="", encoding="utf-8")
        w = csv.writer(out)
        w.writerow(Store.CSV_HEADER)
        w.writerows(store.export_rows(summary["start"], summary["end"],
                                      cfg.site.timezone, cfg.site.reporting.day_start))
        if out is not sys.stdout:
            out.close()
            print(f"wrote {args.csv}")
